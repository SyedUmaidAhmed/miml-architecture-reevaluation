def header(src):
    return (f"%% GENERATED by scripts/dmkd_tables.py from {src}.\n"
            "%% Do not edit numbers by hand; re-run the script.\n")


def fmt(x, nd=3):
    return "--" if x is None else f"{x:.{nd}f}"


def fmt_p(p):
    if p is None:
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def write(name, body):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write(body)


