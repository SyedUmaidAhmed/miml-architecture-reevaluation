def t_numbers(an, cells, ext_counts=None):
    """Every number the prose cites, as LaTeX macros (\\dk...), so the text
    never carries a hand-typed value. Missing values render as a red '??'."""
    import numpy as np
    M = {}
    miss = r"\textcolor{red}{??}"
    def put(name, val, nd=3, pct=False):
        if val is None:
            M[name] = miss
        elif isinstance(val, str):
            M[name] = val
        elif pct:
            M[name] = f"{100 * val:.0f}"
        elif isinstance(val, (int, np.integer)):
            M[name] = str(int(val))
        else:
            M[name] = f"{val:.{nd}f}"
    tag = {"miml_lcga": "Lcga", "abmil_ml": "Abmil", "transformer_pool_ml": "Tpool",
           "mlp_pool_ml": "Mlp", "clam_multilabel_ml": "Clam"}
    mtag = {"AveragePrecision": "AP", "RankingLoss": "RL", "OneError": "OE",
            "Coverage": "Cov", "HammingLoss": "HL"}
    # A1
    for m, mt in mtag.items():
        n_rej = 0
        for a in A.FIVE:
            t = an["A1_objective"][m][a]
            put(f"dkObj{mt}Win{tag[a]}", t.get("wins_a"))
            put(f"dkObj{mt}Loss{tag[a]}", t.get("wins_b"))
            put(f"dkObj{mt}Med{tag[a]}", t.get("median_diff"), 4)
            put(f"dkObj{mt}P{tag[a]}", None if t.get("p_holm") is None else fmt_p(t["p_holm"]))
            if a in A.CORE and t.get("p_holm") is not None and t["p_holm"] < 0.05 \
                    and (t.get("median_diff") or 0) > 0:
                n_rej += 1
        put(f"dkObj{mt}NRejCore", n_rej)
    # A2
    for o in A.OBJS:
        for m, mt in mtag.items():
            r = an["A2_architecture"].get(f"{o}/{m}", {})
            put(f"dkFried{mt}{o.capitalize()}", None if r.get("friedman_p") is None else fmt_p(r["friedman_p"]))
            for a in A.FIVE:
                put(f"dkRank{mt}{o.capitalize()}{tag[a]}", r.get("avg_rank", {}).get(a), 2)
    # A2 post-hoc (Nemenyi, only where Friedman rejected)
    for o in A.OBJS:
        for m, mt in mtag.items():
            r = an["A2_architecture"].get(f"{o}/{m}", {})
            pairs = r.get("nemenyi_significant_pairs")
            put(f"dkNemCD{mt}{o.capitalize()}", r.get("nemenyi_cd"), 2)
            if pairs is None:
                put(f"dkNem{mt}{o.capitalize()}", "no post-hoc test (Friedman did not reject)")
            elif not pairs:
                put(f"dkNem{mt}{o.capitalize()}", "no pair differs by more than the critical difference")
            else:
                by_worse = {}
                for b, w, _ in pairs:
                    by_worse.setdefault(w, []).append(NAMES[b])
                txt = "; ".join(f"{NAMES[w]} ranks worse than " + ", ".join(sorted(bs))
                                for w, bs in by_worse.items())
                put(f"dkNem{mt}{o.capitalize()}", txt)
    # A3
    for o in A.OBJS:
        g = [an["A3_ensemble"]["AveragePrecision"][f"{a}/{o}"].get("median_diff") for a in A.FIVE]
        gc = [x for a, x in zip(A.FIVE, g) if a in A.CORE and x is not None]
        put(f"dkEnsMin{o.capitalize()}", min(gc) if gc else None, 3)
        put(f"dkEnsMax{o.capitalize()}", max(gc) if gc else None, 3)
        ps = [an["A3_ensemble"]["AveragePrecision"][f"{a}/{o}"].get("p_holm") for a in A.FIVE]
        ps = [x for x in ps if x is not None]
        put(f"dkEnsPmax{o.capitalize()}", fmt_p(max(ps)) if ps else None)
        for a in A.FIVE:
            t = an["A3_ensemble"]["AveragePrecision"][f"{a}/{o}"]
            put(f"dkEnsMed{o.capitalize()}{tag[a]}", t.get("median_diff"), 3)
            put(f"dkEnsWin{o.capitalize()}{tag[a]}", t.get("wins_a"))
    # A4
    for m, mt in mtag.items():
        sh = an["A4_variance"][m].get("share", {})
        for k, kt in (("architecture", "Arch"), ("objective", "Obj"),
                      ("architecture_x_objective", "Int"), ("seed_residual", "Seed")):
            put(f"dkVar{mt}{kt}", sh.get(k), pct=True)
            put(f"dkVc{mt}{kt}", an["A4_variance"][m].get("vc_share", {}).get(k), pct=True)
    pdx = an["A4_per_dataset"]
    for o in A.OBJS:
        sp = [v[f"arch_spread_{o}"] for v in pdx.values() if f"arch_spread_{o}" in v]
        eg = [g for v in pdx.values() for k, g in v.get("ensemble_gain", {}).items()
              if k.endswith("/" + o) and k.split("/")[0] in A.CORE]
        put(f"dkSpread{o.capitalize()}", float(np.median(sp)) if sp else None, 3)
        put(f"dkGain{o.capitalize()}", float(np.median(eg)) if eg else None, 3)
    og = [g for v in pdx.values() for a, g in v.get("objective_gap", {}).items()]
    put("dkObjGapMed", float(np.median(og)) if og else None, 4)
    for o in A.OBJS:
        sp5 = []
        for ds in A.DATASETS:
            ms = [A.seed_table(cells, a, o, "AveragePrecision").get(ds) for a in A.FIVE]
            if all(ms):
                sp5.append(max(m[0] for m in ms) - min(m[0] for m in ms))
        put(f"dkSpreadFive{o.capitalize()}", float(np.median(sp5)) if sp5 else None, 3)
    for a in A.FIVE:
        b = A.seed_table(cells, a, "bce", "AveragePrecision")
        r = A.seed_table(cells, a, "rankasl", "AveragePrecision")
        n_big = sum(1 for ds in b if ds in r and
                    abs(r[ds][0] - b[ds][0]) > np.sqrt((b[ds][1] ** 2 + r[ds][1] ** 2) / 2))
        put(f"dkObjBigN{tag[a]}", n_big)
    # A5
    for k, kt in (("K4_vs_K1_bce", "Bce"), ("K4_vs_K1_rankasl", "Rank"),
                  ("K4_vs_attn128_rankasl", "Wide")):
        t = an["A5_moe"]["AveragePrecision"][k]
        put(f"dkMoe{kt}Med", t.get("median_diff"), 4)
        put(f"dkMoe{kt}Win", t.get("wins_a"))
        put(f"dkMoe{kt}Loss", t.get("wins_b"))
        put(f"dkMoe{kt}P", None if t.get("p_holm") is None else fmt_p(t["p_holm"]))
        put(f"dkMoe{kt}N", t.get("n"))
    # A6: datasets (of those with reference learners) where some reference
    # learner beats every neural configuration, per metric
    a6 = an["A6_external"]
    for m, mt in mtag.items():
        n_ds, n_beaten = 0, 0
        names = []
        for ds in A.DATASETS:
            if ds not in a6:
                continue
            n_ds += 1
            confs = a6[ds]
            beaten = any(all(not confs[c][ext][m]["neural_better"] for c in confs)
                         for ext in next(iter(confs.values())))
            if beaten:
                n_beaten += 1
                names.append(DSN[ds])
        put(f"dkExtN{mt}", n_ds)
        put(f"dkExtBeaten{mt}", n_beaten)
        put(f"dkExtBeatenNames{mt}", ", ".join(names) if names else "none")
    # objective effect on the ten datasets NOT used by the pre-study screen
    screen = {"scene", "mscv2", "protein_pyrococcus"}
    for a in A.FIVE:
        b = A.seed_table(cells, a, "bce", "AveragePrecision")
        r = A.seed_table(cells, a, "rankasl", "AveragePrecision")
        other = [r[ds][0] - b[ds][0] for ds in b if ds in r and ds not in screen]
        put(f"dkObjOtherWin{tag[a]}", sum(1 for x in other if x > 0) if other else None)
        put(f"dkObjOtherN{tag[a]}", len(other) if other else None)
    if ext_counts:
        put("dkExtBeatenEnsAP", ext_counts["ens"])
        put("dkExtBeatenEnsNamesAP", ", ".join(ext_counts["ens_names"]) or "none")
        put("dkExtNAll", ext_counts["n"])
        put("dkExtBeatenSingleAll", ext_counts["single"])
        for g, gt in (("native", "Native"), ("framed", "Framed")):
            n, s1, e1, nm = ext_counts["groups"][g]
            put(f"dkExtN{gt}", n)
            put(f"dkExtSingle{gt}", s1)
            put(f"dkExtEns{gt}", e1)
            put(f"dkExtSingleNames{gt}", ", ".join(nm) or "none")
    put("dkNcells", an.get("n_cells"))
    body = header("analysis.json") + "\n".join(
        f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(M.items())) + "\n"
    write("gen_numbers.tex", body)


